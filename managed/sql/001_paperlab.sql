-- Private schema and narrowly exposed RPCs. Run as project administrator.
begin;
create schema if not exists paperlab;
comment on schema paperlab is 'PaperLab managed-v1';
revoke all on schema paperlab from public, anon, authenticated;
create table if not exists paperlab.settings (
  singleton boolean primary key default true check(singleton),
  owner_id uuid, origin text, installed_at timestamptz not null default now()
);
insert into paperlab.settings(singleton) values(true) on conflict do nothing;
create table if not exists paperlab.portfolio (
  singleton boolean primary key default true check(singleton),
  state jsonb not null, revision bigint not null default 1,
  lease uuid, lease_until timestamptz, last_attempt timestamptz,
  last_tick_status text not null default 'not_started'
);
create table if not exists paperlab.trades (
  id bigint generated by default as identity primary key,
  time timestamptz not null, symbol text not null, side text not null check(side in ('koop','verkoop')),
  qty double precision not null check(qty>0), price double precision not null check(price>0),
  fee double precision not null check(fee>=0), pnl double precision not null,
  reason text not null, snapshot jsonb not null
);
create table if not exists paperlab.events (
  id bigint generated by default as identity primary key,time timestamptz not null,
  kind text not null,symbol text not null default '',reason text not null,data jsonb not null default '{}'
);
create table if not exists paperlab.equity (
  id bigint generated by default as identity primary key,time timestamptz not null,
  value double precision not null,benchmark double precision not null
);
create table if not exists paperlab.observations (
  id bigint generated by default as identity primary key,received timestamptz not null,
  symbol text not null,source text not null,quote_time timestamptz not null,payload jsonb not null,fx jsonb not null
);
create index if not exists observations_received on paperlab.observations(received);
create table if not exists paperlab.sessions (
  id uuid primary key,created_at timestamptz not null default now(),seen_at timestamptz not null default now(),revoked boolean not null default false
);
create table if not exists paperlab.recovery (
  hash text primary key check(length(hash)=64),used_at timestamptz,created_at timestamptz not null default now()
);
create table if not exists paperlab.research (
  id bigint generated by default as identity primary key,time timestamptz not null default now(),report jsonb not null
);
create table if not exists paperlab.free_usage (
  month date primary key,tick_attempts integer not null default 0,
  estimated_worker_egress_bytes bigint not null default 0,
  max_tick_attempts integer not null default 10000 check(max_tick_attempts between 1 and 10000),
  max_worker_egress_bytes bigint not null default 3000000000 check(max_worker_egress_bytes between 1 and 3000000000),
  max_database_bytes bigint not null default 300000000 check(max_database_bytes between 1 and 300000000)
);
do $$declare n text;begin
  foreach n in array array['settings','portfolio','trades','events','equity','observations','sessions','recovery','research','free_usage'] loop
    execute format('alter table paperlab.%I enable row level security',n);
    execute format('revoke all on paperlab.%I from public, anon, authenticated, service_role',n);
  end loop;
end$$;

create or replace function public.paper_context() returns jsonb
language sql security definer set search_path=pg_catalog,pg_temp as $$
  select jsonb_build_object('owner_id',owner_id,'origin',origin) from paperlab.settings where singleton;
$$;

create or replace function public.paper_session(p_owner uuid,p_session uuid,p_revoke boolean default false) returns boolean
language plpgsql security definer set search_path=pg_catalog,pg_temp as $$
declare r paperlab.sessions;
begin
  if p_owner is distinct from (select owner_id from paperlab.settings where singleton) then return false;end if;
  insert into paperlab.sessions(id) values(p_session) on conflict do nothing;
  select * into r from paperlab.sessions where id=p_session for update;
  if p_revoke then update paperlab.sessions set revoked=true where id=p_session;return false;end if;
  if r.revoked or now()-r.created_at>interval '8 hours' or now()-r.seen_at>interval '30 minutes' then return false;end if;
  update paperlab.sessions set seen_at=now() where id=p_session;
  return true;
end$$;

create or replace function public.paper_read(p_owner uuid,p_revision bigint default -1) returns jsonb
language plpgsql security definer set search_path=pg_catalog,pg_temp as $$
declare p paperlab.portfolio;s jsonb;v double precision;
begin
  if p_owner is distinct from (select owner_id from paperlab.settings where singleton) then raise exception 'Not owner';end if;
  select * into p from paperlab.portfolio where singleton;
  if not found then return jsonb_build_object('not_initialized',true);end if;
  if p.revision=p_revision then return jsonb_build_object('unchanged',true,'revision',p.revision,'server_time',now(),'collector_status',p.last_tick_status);end if;
  s=p.state-'history'-'oracle_handoff';s=jsonb_set(s,'{risk}',(s->'risk')-'previous_quotes');
  select coalesce(sum((x.value->>'qty')::double precision*(p.state->'prices'->>x.key)::double precision/
    coalesce((p.state->'price_fx'->>x.key)::double precision,(p.state->>'usd_per_eur')::double precision)),0)
    into v from jsonb_each(p.state->'positions') x;
  return jsonb_build_object('revision',p.revision,'state',s,'equity',(s->>'cash')::double precision+v,
    'collector_status',p.last_tick_status,'last_attempt',p.last_attempt,'server_time',now(),
    'trades',(select coalesce(jsonb_agg(q order by q.id desc),'[]'::jsonb) from
      (select id,time,symbol,side,qty,price,fee,pnl,reason,snapshot->>'currency' currency,snapshot->'tax_detail' tax_detail,
      snapshot->>'strategy_version' strategy_version from paperlab.trades order by id desc limit 100) q),
    'trade_count',(select count(*) from paperlab.trades),
    'curve',(select coalesce(jsonb_agg(q order by q.id),'[]'::jsonb) from(select * from paperlab.equity order by id desc limit 500) q),
    'events',(select coalesce(jsonb_agg(q order by q.id desc),'[]'::jsonb) from(select id,time,kind,symbol,reason from paperlab.events order by id desc limit 60) q),
    'research',(select report from paperlab.research order by id desc limit 1),
    'free_usage',jsonb_build_object('database_bytes',pg_database_size(current_database()),
      'automatic_budget',(select to_jsonb(u) from paperlab.free_usage u where month=date_trunc('month',now() at time zone 'UTC')::date),
      'note','Raming van automatische verwerking, geen volledige providerfactuur. Controleer ook de usage-paginas.'));
end$$;

create or replace function public.paper_receipt(p_owner uuid,p_id bigint) returns jsonb
language plpgsql security definer set search_path=pg_catalog,pg_temp as $$
begin
  if p_owner is distinct from (select owner_id from paperlab.settings where singleton) then raise exception 'Not owner';end if;
  return(select jsonb_build_object('id',id,'time',time,'symbol',symbol,'side',side,'qty',qty,'price',price,'fee',fee,'pnl',pnl,'reason',reason,'snapshot',snapshot) from paperlab.trades where id=p_id);
end$$;

create or replace function public.paper_export(p_owner uuid) returns jsonb
language plpgsql security definer set search_path=pg_catalog,pg_temp as $$
begin
  if p_owner is distinct from(select owner_id from paperlab.settings where singleton) then raise exception 'Not owner';end if;
  return(select coalesce(jsonb_agg(q order by q.id),'[]'::jsonb) from
    (select id,time,symbol,side,qty,price,fee,pnl,reason,snapshot->>'currency' currency,snapshot->>'fx' fx,snapshot->'tax_detail' tax_detail,snapshot->>'strategy_version' strategy_version from paperlab.trades order by id) q);
end$$;

create or replace function public.paper_action(p_owner uuid,p_action text) returns boolean
language plpgsql security definer set search_path=pg_catalog,pg_temp as $$
declare s jsonb;
begin
  if p_owner is distinct from(select owner_id from paperlab.settings where singleton) then raise exception 'Not owner';end if;
  if p_action not in('start','pause') then raise exception 'Unsupported action';end if;
  select state into s from paperlab.portfolio where singleton for update;
  if p_action='start' and ((s->>'run_until')::timestamptz<=now() or s->>'mode'<>'yahoo' or s->'risk'->>'enabled'<>'true' or s->'belgian_tax'->>'enabled'<>'true') then raise exception 'Trial ended or profile invalid';end if;
  update paperlab.portfolio set state=jsonb_set(state,'{running}',to_jsonb(p_action='start')),revision=revision+1,lease=null,lease_until=null where singleton;
  insert into paperlab.events(time,kind,reason) values(now(),'bediening',case when p_action='start' then 'Eigenaar hervat de paperproef.' else 'Eigenaar pauzeert de paperproef.' end);
  return true;
end$$;

create or replace function public.paper_claim_tick(p_manual boolean default false) returns jsonb
language plpgsql security definer set search_path=pg_catalog,pg_temp as $$
declare p paperlab.portfolio;t uuid;u paperlab.free_usage;m date;charge bigint;
begin
  select * into p from paperlab.portfolio where singleton for update;
  if not found then return null;end if;
  if (p.state->>'run_until')::timestamptz<=now() then
    update paperlab.portfolio set state=jsonb_set(state,'{running}','false'),last_tick_status='trial_ended',revision=revision+1 where singleton;return null;
  end if;
  if coalesce((p.state->>'running')::boolean,false)=false and not p_manual then return null;end if;
  if p.lease_until>now() or p.last_attempt>now()-interval '45 seconds' then return null;end if;
  m:=date_trunc('month',now() at time zone 'UTC')::date;
  insert into paperlab.free_usage(month) values(m) on conflict do nothing;
  select * into u from paperlab.free_usage where month=m for update;
  -- Deliberately conservative application estimate, not provider billing data.
  -- Covers repeated state transfers plus a fixed per-attempt overhead.
  charge:=4*(octet_length(p.state::text)+16384);
  if u.tick_attempts>=u.max_tick_attempts or u.estimated_worker_egress_bytes+charge>u.max_worker_egress_bytes or pg_database_size(current_database())>=u.max_database_bytes then
    update paperlab.portfolio set state=jsonb_set(jsonb_set(state,'{running}','false'),'{error}',to_jsonb('Automatisch gepauzeerd om gratis verbruikslimieten te beschermen. Controleer opslag en providergebruik voordat je hervat.'::text)),
      revision=revision+1,lease=null,lease_until=null,last_attempt=now(),last_tick_status='free_budget_paused' where singleton;
    insert into paperlab.events(time,kind,reason) values(now(),'verbruik','Gratis verbruiksbudget bereikt; automatische handel gepauzeerd. Geen upgrade of betaling uitgevoerd.');
    return null;
  end if;
  update paperlab.free_usage set tick_attempts=tick_attempts+1,estimated_worker_egress_bytes=estimated_worker_egress_bytes+charge where month=m;
  t=gen_random_uuid();
  update paperlab.portfolio set lease=t,lease_until=now()+interval '120 seconds',last_attempt=now(),last_tick_status='measuring' where singleton;
  return jsonb_build_object('token',t,'revision',p.revision,'state',jsonb_set(p.state,'{running}','true'),'persist_running',p.state->'running');
end$$;

create or replace function public.paper_commit_tick(p_token uuid,p_revision bigint,p_output jsonb) returns boolean
language plpgsql security definer set search_path=pg_catalog,pg_temp as $$
declare p paperlab.portfolio;s jsonb;expected double precision;fees double precision;realized double precision;
begin
  select * into p from paperlab.portfolio where singleton for update;
  if p_token is null or p_revision is null or p.lease is null or p.lease_until is null or p.lease is distinct from p_token or p.revision<>p_revision or p.lease_until<=now() then return false;end if;
  s=p_output->'state';
  if s is null or jsonb_typeof(s)<>'object' or s->>'mode' is distinct from 'yahoo' or coalesce(jsonb_array_length(s->'universe'),0)<>100 or jsonb_array_length(coalesce(p_output->'trades','[]'))>20 then raise exception 'Invalid tick';end if;
  insert into paperlab.trades(time,symbol,side,qty,price,fee,pnl,reason,snapshot)
    select (x->>'time')::timestamptz,x->>'symbol',x->>'side',(x->>'qty')::double precision,(x->>'price')::double precision,
    (x->>'fee')::double precision,(x->>'pnl')::double precision,x->>'reason',x->'snapshot' from jsonb_array_elements(coalesce(p_output->'trades','[]')) x;
  select 500+coalesce(sum(case when side='koop' then -qty*price/(snapshot->>'fx')::double precision else qty*price/(snapshot->>'fx')::double precision end-fee
    -coalesce((snapshot->'tax_detail'->>'transaction_tax_eur')::double precision,0)-coalesce((snapshot->'tax_detail'->>'capital_gains_reserve_eur')::double precision,0)
    -coalesce((snapshot->'tax_detail'->>'foreign_tax_reserve_eur')::double precision,0)-coalesce((snapshot->'tax_detail'->>'adr_reserve_eur')::double precision,0)),0),
    coalesce(sum(fee),0),coalesce(sum(pnl),0) into expected,fees,realized from paperlab.trades;
  if abs((s->>'cash')::double precision-expected)>0.000001 or abs((s->>'fees')::double precision-fees)>0.000001 or abs((s->>'realized')::double precision-realized)>0.000001 or (s->>'cash')::double precision<0 then raise exception 'Ledger mismatch';end if;
  insert into paperlab.events(time,kind,symbol,reason,data)
    select (x->>'time')::timestamptz,x->>'kind',coalesce(x->>'symbol',''),x->>'reason',coalesce(x->'data','{}') from jsonb_array_elements(coalesce(p_output->'events','[]')) x;
  insert into paperlab.observations(received,symbol,source,quote_time,payload,fx)
    select (x->>'received')::timestamptz,x->>'symbol',x->>'source',(x->>'quote_time')::timestamptz,x->'payload',x->'fx' from jsonb_array_elements(coalesce(p_output->'observations','[]')) x;
  if p_output->'equity' is not null and p_output->'equity'<>'null' then
    insert into paperlab.equity(time,value,benchmark) values((p_output->'equity'->>'time')::timestamptz,(p_output->'equity'->>'value')::double precision,(p_output->'equity'->>'benchmark')::double precision);
  end if;
  update paperlab.portfolio set state=s,revision=revision+1,lease=null,lease_until=null,
    last_tick_status=case when s->>'error' is not null then 'partial_or_waiting' else 'collecting' end where singleton;
  -- Raw data is bounded; trade receipts and equity/audit histories are retained.
  if (s->>'tick')::integer%12=0 then
    delete from paperlab.observations where received<now()-interval '2 days';
    delete from paperlab.events where kind in('wacht','fout') and time<now()-interval '7 days';
  end if;
  return true;
end$$;

create or replace function public.paper_fail_tick(p_token uuid,p_message text) returns boolean
language plpgsql security definer set search_path=pg_catalog,pg_temp as $$
begin
  update paperlab.portfolio set lease=null,lease_until=null,last_tick_status='error',
    state=jsonb_set(state,'{error}',to_jsonb(left(p_message,250))),revision=revision+1 where singleton and lease=p_token;
  return found;
end$$;

create or replace function public.paper_recovery(p_owner uuid,p_action text,p_hashes jsonb default '[]',p_hash text default '') returns boolean
language plpgsql security definer set search_path=pg_catalog,pg_temp as $$
begin
  if p_owner is distinct from(select owner_id from paperlab.settings where singleton) then raise exception 'Not owner';end if;
  if p_action='create' then
    if jsonb_array_length(p_hashes)<>10 then raise exception 'Expected ten hashes';end if;
    delete from paperlab.recovery;
    insert into paperlab.recovery(hash) select value from jsonb_array_elements_text(p_hashes);
    return true;
  elsif p_action='consume' then
    update paperlab.recovery set used_at=now() where hash=p_hash and used_at is null;
    return found;
  end if;
  return false;
end$$;

create or replace function public.paper_research(p_report jsonb) returns boolean
language plpgsql security definer set search_path=pg_catalog,pg_temp as $$
begin
  insert into paperlab.research(report) values(p_report);
  delete from paperlab.research where time<now()-interval '14 days';
  return true;
end$$;

do $$declare f record;begin
  for f in select p.oid::regprocedure as signature from pg_proc p join pg_namespace n on n.oid=p.pronamespace where n.nspname='public' and p.proname like 'paper\_%' escape '\' loop
    execute format('revoke all on function %s from public, anon, authenticated',f.signature);
    execute format('grant execute on function %s to service_role',f.signature);
  end loop;
end$$;
commit;
